def char_bytes(rows):
    out = []
    for fila in rows:
        b = 0
        for x, ch in enumerate(fila):
            if ch == '#':
                b |= (0x80 >> x)
        out.append(b)
    return out


def build_table():
    """Devuelve 1024 bytes: 128 caracteres x 8 filas (1bpp)."""
    data = [0] * 1024
    for code in range(0x20, 0x80):
        ch = chr(code)
        key = 'DEL' if code == 0x7F else ch
        rows = FONT.get(key)
        if rows is None:
            continue
        for i, b in enumerate(char_bytes(rows)):
            data[(code - 0x20) * 8 + i] = b
    return data


def emit_inc():
    data = build_table()
    print("; generado por mk_font.py -- fuente 8x8 1bpp, ASCII $20..$7F")
    print("; direccion = (ascii - $20) * 8 + fila   (0..767)")
    print("font_data:")
    for i in range(0, len(data), 16):
        fila = ", ".join(f"${b:02X}" for b in data[i:i+16])
        print(f"    .byte {fila}")


def emit_vhd(path):
    data = build_table()
    lines = []
    lines.append("-- ======================================================")
    lines.append("-- font_data.vhd -- banco de fuente 8x8 1bpp (generado)")
    lines.append("-- 1024 entradas x 9 bits; usadas 768 (96 chars x 8 filas)")
    lines.append("-- ======================================================")
    lines.append("")
    lines.append("library ieee;")
    lines.append("use ieee.std_logic_1164.all;")
    lines.append("use ieee.numeric_std.all;")
    lines.append("")
    lines.append("package font_pkg is")
    lines.append("    type font_init_t is array (0 to 1023) of std_logic_vector(8 downto 0);")
    lines.append("    constant FONT_INIT : font_init_t := (")
    for i, b in enumerate(data):
        comma = "," if i < len(data) - 1 else ""
        lines.append(f'        {i} => "0" & x"{b:02X}"{comma}')
    lines.append("    );")
    lines.append("end package;")
    lines.append("")
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"OK: {path} generado ({len(data)} entradas)")


if __name__ == "__main__":
    import sys
    if len(sys.argv) > 2 and sys.argv[1] == "vhd":
        emit_vhd(sys.argv[2])
    else:
        emit_inc()
